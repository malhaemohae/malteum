const assert = require('node:assert/strict');
const fs = require('node:fs'); const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || path.join(process.env.USERPROFILE, '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
const { allSizes, failures, checks } = require('./workspace-qa.cjs');
const fixture = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../../back/contracts/fixtures/ws_messages.json'), 'utf8'));
const ready = fixture.find(m => m.t === 'ready');
const out = path.resolve(__dirname, '../qa-output'); fs.mkdirSync(out, { recursive: true });
const result = { scope: 'real GETs; isolated writes and exact committed WS fixtures', messages: [], errors: [], checks: [] };
let browser;
(async () => {
  browser = await chromium.launch({ headless: true, args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, permissions: ['microphone'] });
  const page = await context.newPage(); page.setDefaultTimeout(20000);
  page.on('pageerror', e => result.errors.push(e.message));
  let client; let frames = 0; let pdfRequests = 0;
  await context.route('**/api/**', route => {
    const req = route.request(); const url = new URL(req.url());
    if (url.pathname.endsWith('/report.pdf')) pdfRequests++;
    if (req.method() === 'GET') return route.continue();
    if (req.method() === 'POST' && url.pathname === '/api/sessions') return route.fulfill({ status: 201, json: { session_id: ready.session_id, pack_version: ready.pack_version, ws_url: '/ws' } });
    result.errors.push(`Unexpected mutation ${req.method()} ${url.pathname}`); return route.abort();
  });
  await page.routeWebSocket(/.*/, ws => {
    let app = false;
    ws.onMessage(data => {
      if (typeof data !== 'string') { if (app) frames++; return; }
      const m = JSON.parse(data); if (!m.t) return;
      result.messages.push(m);
      if (m.t === 'hello') { app = true; client = ws; ws.send(JSON.stringify(ready)); }
    });
  });
  await page.goto('http://localhost:3000', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: /상담 시작|시작하기|대시보드/ }).first().click();
  await page.getByRole('button', { name: '상담 시작 →', exact: true }).waitFor();
  assert.ok(await page.getByText('시연 입력은 외부 STT·AI 서비스에서 처리됩니다.', { exact: false }).isVisible());
  await allSizes(page, 'feedback-briefing');
  await page.getByRole('button', { name: '상담 시작 →', exact: true }).click();
  const cards = page.locator('.wb-shortcuts');
  await page.waitForFunction(() => !!document.querySelector('.wb-shortcut.is-record') && !document.querySelector('.wb-shortcut.is-record').disabled);
  await cards.getByRole('button', { name: '● 녹음 시작', exact: true }).click();
  await cards.getByRole('button', { name: '■ 녹음 중지', exact: true }).waitFor();
  for (let n = 0; frames < 2 && n < 50; n++) await page.waitForTimeout(100);
  assert.ok(frames > 0);
  await cards.getByRole('button', { name: '■ 녹음 중지', exact: true }).click();
  assert.ok(await page.locator('.wb-transcript').evaluate(el => el.classList.contains('wb-pulse')));
  result.checks.push('microphone toggles and destination pulses');
  await allSizes(page, 'feedback-dashboard');
  const before = result.messages.length;
  await cards.getByRole('button', { name: '필요 서류', exact: true }).click();
  await page.getByRole('dialog', { name: '필요 서류', exact: true }).waitFor();
  assert.ok(await page.getByText('실명확인증표', { exact: true }).isVisible());
  await allSizes(page, 'feedback-documents-reference');
  await page.getByRole('dialog').getByRole('button', { name: '닫기', exact: true }).click();
  await cards.getByRole('button', { name: '상담 기준', exact: true }).click();
  await page.getByRole('dialog', { name: '상담 기준', exact: true }).waitFor();
  await allSizes(page, 'feedback-pack-reference');
  await page.getByRole('dialog').getByRole('button', { name: '닫기', exact: true }).click();
  assert.equal(result.messages.length, before, 'static references never require WS or create assist events');
  result.checks.push('documents and applied pack open immediately without WS');
  await cards.getByRole('button', { name: '필수 안내', exact: true }).click();
  await allSizes(page, 'shallow-checklist-actions');
  await page.locator('[data-check-item="DEP-INT-002"]').getByRole('button', { name: '쉬운 말', exact: true }).click();
  await page.getByRole('dialog', { name: '쉬운 말 안내', exact: true }).waitFor();
  assert.equal(await page.locator('dialog[open]').count(), 1, 'direct rephrase has no intermediate detail dialog');
  assert.ok(await page.getByRole('button', { name: '응답 기다리는 중…', exact: true }).isDisabled());
  client.send(JSON.stringify(fixture.find(m => m.t === 'alert' && m.alert_type === 'risk_signal')));
  client.send(JSON.stringify(fixture.find(m => m.t === 'assist' && m.assist_type === 'rephrase')));
  await page.getByRole('dialog').getByText('쉬운 말 안내가 도착했습니다.', { exact: true }).waitFor();
  assert.ok(await page.getByRole('dialog').locator('[data-reader-copy]').getByText('만기 전에 찾으면 약속한 이자보다 적게 받습니다.', { exact: true }).isVisible());
  await allSizes(page, 'feedback-rephrase-result');
  await page.getByRole('dialog').getByRole('button', { name: '다시 요청', exact: true }).click();
  client.send(JSON.stringify(fixture.find(m => m.t === 'error')));
  await page.getByRole('dialog').getByText('음성 인식을 쓸 수 없습니다.', { exact: false }).waitFor();
  assert.ok(await page.getByRole('button', { name: '다시 요청', exact: true }).isEnabled());
  await page.getByRole('dialog').getByRole('button', { name: '닫기', exact: true }).click();
  await page.getByRole('button', { name: /안내 \d+건 보기/ }).click();
  assert.ok(await page.getByRole('heading', { name: '위험 신호', exact: true }).isVisible());
  result.checks.push('manual rephrase is visible despite checks tab and higher-priority risk; waiting and errors are explicit; risk remains');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await cards.getByRole('button', { name: '필수 안내', exact: true }).click();
  assert.equal(await page.locator('.wb-checks>.wb-panel').evaluate(el => getComputedStyle(el).animationName), 'none');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.locator('[data-paged-list="필수 안내"] .wb-row-button').first().click();
  await page.getByRole('button', { name: '근거 원문', exact: true }).click();
  await page.getByRole('dialog', { name: '근거 원문', exact: true }).getByRole('link', { name: /출처 원문 열기/ }).waitFor();
  await page.waitForFunction(() => document.querySelector('.wb-page-canvas img')?.naturalWidth > 0);
  assert.ok(await page.locator('.wb-evidence-content [data-reader-copy]').isVisible());
  assert.equal(await page.locator('dialog[open]').count(), 1);
  await allSizes(page, 'feedback-evidence');
  const fitted = await page.locator('.wb-page-canvas img').evaluate(img => { const r = img.getBoundingClientRect(); return Math.abs(r.width / r.height - img.naturalWidth / img.naturalHeight) < .02; });
  assert.ok(fitted, 'PDF canvas keeps its original ratio, including highlight coordinates');
  await page.getByRole('dialog', { name: '근거 원문', exact: true }).getByRole('button', { name: '닫기', exact: true }).click();
  assert.equal(await page.locator('dialog[open]').count(), 0, 'evidence closes directly to the dashboard, not a stacked detail modal');
  await page.getByRole('navigation', { name: '주 메뉴' }).getByRole('button', { name: '리포트', exact: true }).click();
  await page.getByRole('button', { name: 'PDF 저장', exact: true }).waitFor();
  await page.getByRole('button', { name: '타임라인', exact: true }).click();
  assert.ok(!(await page.locator('[data-paged-list="리포트"]').innerText()).includes('→ met'));
  const pdfResponse = page.waitForResponse(response => response.url().endsWith('/report.pdf'));
  const popupPromise = context.waitForEvent('page');
  await page.getByRole('button', { name: 'PDF 저장', exact: true }).click();
  const popup = await popupPromise;
  const pdf = await pdfResponse; assert.equal(pdf.status(), 200);
  assert.equal((await pdf.body()).subarray(0, 5).toString(), '%PDF-');
  await popup.getByRole('link', { name: '서버 원본 PDF 다운로드', exact: true }).waitFor();
  assert.ok(!(await popup.locator('body').innerText()).includes('→ met'));
  const downloadPromise = popup.waitForEvent('download');
  await popup.getByRole('link', { name: '서버 원본 PDF 다운로드', exact: true }).click();
  const download = await downloadPromise; assert.equal(await download.failure(), null);
  await popup.close();
  await context.route('**/api/sessions/*/report.pdf', route => route.fulfill({ status: 404, json: { detail: 'isolated fallback test' } }));
  const fallbackPromise = context.waitForEvent('page');
  await page.getByRole('button', { name: 'PDF 저장', exact: true }).click();
  const fallback = await fallbackPromise;
  await fallback.getByText('서버 PDF를 가져오지 못해', { exact: false }).waitFor();
  assert.ok(pdfRequests > 0); assert.ok(!(await fallback.locator('body').innerText()).includes('→ met'));
  assert.ok((await fallback.locator('body').innerText()).includes('고지 완료'));
  await fallback.close(); await allSizes(page, 'feedback-report');
  result.checks.push('source URLs, reduced motion, translated report/print, real server PDF success and isolated 404 print fallback');
  assert.deepEqual(result.errors, []); assert.deepEqual(failures, []);
  result.layoutCount = checks.length;
  fs.writeFileSync(path.join(out, 'final-feedback-qa.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { fs.writeFileSync(path.join(out, 'final-feedback-layout.json'), JSON.stringify({ checks, failures }, null, 2)); await browser?.close(); });
