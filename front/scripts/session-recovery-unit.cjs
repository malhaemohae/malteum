let active = recoveredSession(detail, pack, events);
const handshake = sessionHandshake(active, true, 'general');
assert.equal(handshake.hello.t, 'hello');
assert.equal(handshake.hello.session_id, detail.session_id, 'transport binds the same record');
assert.equal(handshake.hello.customer_profile, undefined, 'recovery must not replace the original customer profile');
assert.equal(handshake.ready({t:'ping'}).resume, undefined);
const handshakeReady = handshake.ready({...ready,seq:100});
assert.deepEqual(handshakeReady.resume, {t:'resume', session_id:active.id, from_seq:0});
assert.equal(handshakeReady.message.seq, undefined, 'new ready must not suppress older recovery events');
assert.equal(handshake.ready(ready).resume, undefined, 'replayed ready cannot create a resume loop');
const freshHandshake = sessionHandshake(active, false, 'professional');
assert.equal(freshHandshake.hello.customer_profile.type, 'professional');
assert.equal(freshHandshake.ready(ready).resume, undefined, 'fresh consultation does not request a replay');
const reconnect = sessionHandshake({...active,seq:42}, false, 'general');
assert.equal(reconnect.ready(ready).resume.from_seq,42,'same-document retry retains the WS cursor');
assert.equal(active.seq, -1, 'REST sequence must never masquerade as WS sequence');
assert.equal(active.progress, undefined, 'progress is server-owned');
assert.equal(active.transcript.length, events.filter(e=>e.kind==='utterance').length);
for (const line of active.transcript) assert.equal(line.text, events.find(e=>e.event_id===line.id).utterance.text);
const line = active.transcript[0];
assert.equal(reduceServer(active, {t:'utterance',seq:1,event_id:line.id,text:line.text,speaker:line.speaker,t_ms:line.t_ms}).transcript.length, active.transcript.length, 'restored transcript is not duplicated by WS replay');
